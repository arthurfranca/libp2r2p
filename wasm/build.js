// Node-only WASM build driver.
import { execFileSync } from 'node:child_process'
import {
  mkdtempSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync
} from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const image = 'libp2r2p-secp256k1-wasm'
const outputDirectory = path.join(root, 'helpers/secp256k1-wasm')
const temporary = mkdtempSync(path.join(tmpdir(), 'libp2r2p-wasm-'))

function findEngine () {
  if (process.env.WASM_CONTAINER_ENGINE) return process.env.WASM_CONTAINER_ENGINE
  for (const engine of ['podman', 'docker']) {
    try {
      execFileSync(engine, ['--version'], { stdio: 'ignore' })
      return engine
    } catch {}
  }
  throw Error('WASM_CONTAINER_ENGINE must name podman or docker')
}

function parseSymbols (source) {
  return Object.fromEntries(
    source
      .trim()
      .split(/\r?\n/)
      .map(line => {
        const [alias, name] = line.split(':', 2)
        return [name, alias]
      })
  )
}

try {
  const engine = findEngine()
  execFileSync(
    engine,
    ['build', '-f', path.join(root, 'wasm/Containerfile'), '-t', image, root],
    { stdio: 'inherit' }
  )
  execFileSync(
    engine,
    ['run', '--rm', '-v', `${temporary}:/out:Z`, image],
    { stdio: 'inherit' }
  )

  const wasm = readFileSync(path.join(temporary, 'secp256k1.wasm'))
  const symbols = parseSymbols(
    readFileSync(path.join(temporary, 'secp256k1.symbols'), 'utf8')
  )
  const names = {
    malloc: symbols.malloc,
    free: symbols.free,
    hash_ctx_init: symbols.secp256k1_hash_ctx_init,
    sha256_initialize: symbols.secp256k1_sha256_initialize,
    sha256_write: symbols.secp256k1_sha256_write,
    sha256_finalize: symbols.secp256k1_sha256_finalize,
    context_create: symbols.secp256k1_context_create,
    xonly_pubkey_parse: symbols.secp256k1_xonly_pubkey_parse,
    xonly_pubkey_serialize: symbols.secp256k1_xonly_pubkey_serialize,
    keypair_create: symbols.secp256k1_keypair_create,
    keypair_xonly_pub: symbols.secp256k1_keypair_xonly_pub,
    schnorrsig_sign32: symbols.secp256k1_schnorrsig_sign32,
    schnorrsig_verify: symbols.secp256k1_schnorrsig_verify,
    memory: symbols.memory,
    init: symbols.__wasm_call_ctors
  }
  const imports = {
    fd_write: symbols.fd_write,
    resize: symbols.emscripten_resize_heap,
    abort: symbols._abort_js
  }
  for (const [name, value] of Object.entries({ ...names, ...imports })) {
    if (!value) throw Error(`Missing WASM symbol: ${name}`)
  }

  mkdirSync(outputDirectory, { recursive: true })
  writeFileSync(
    path.join(outputDirectory, 'generated.js'),
    '// Generated by npm run build:wasm. Do not edit manually.\n' +
      '// Includes libsecp256k1 under the MIT license; see THIRD_PARTY_NOTICES.md.\n' +
      `export const wasmBase64 = ${JSON.stringify(wasm.toString('base64'))}\n` +
      `export const wasmExports = ${JSON.stringify(names, null, 2)}\n` +
      `export const wasmImports = ${JSON.stringify(imports, null, 2)}\n`
  )
  console.log(`Generated ${path.relative(root, outputDirectory)}/generated.js`)
} finally {
  rmSync(temporary, { recursive: true, force: true })
}
